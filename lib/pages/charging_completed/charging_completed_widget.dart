    // On page load action.
    SchedulerBinding.instance.addPostFrameCallback((_) async {
      _model.apiResTransaction =
          await SteveOCCPExtApiGroup.getChargeDataByTransactionCall.call(
        transactionPk: widget.transactionId,
      );

      if ((_model.apiResTransaction?.succeeded ?? true)) {
        _model.startValue =
