          (_model.apiResTransaction?.jsonBody ?? ''),
        )!;
        _model.stopValue =
            SteveOCCPExtApiGroup.getChargeDataByTransactionCall.stopValue(
          (_model.apiResTransaction?.jsonBody ?? ''),
        )!;
        safeSetState(() {});
        _model.getExpenseSummary = await actions.calculateChargingCost(
          _model.startValue,
          int.tryParse(_model.stopValue) ?? 0,
          0.001,
          widget.pricePerKWh!,
        );
        _model.apiResCharge = await SteveOCCPExtApiGroup.chargeCall.call(
          userId: currentUserUid,
          amount: getJsonField(
            _model.getExpenseSummary,
            r'''$.cost''',
          ),
          description:
              'Transaction :  ${widget.transactionId} |  Charging Mode : ${widget.chargingMode == 'byAmount' ? 'Charging ${formatNumber(
                  FFAppState().setAmountCharger,
                  formatType: FormatType.decimal,
                  decimalType: DecimalType.periodDecimal,
                )}  baht' : 'Auto Full Charge (100%)'} | Terminal : ${widget.chargingTerminal}',
        );

        if ((_model.apiResCharge?.succeeded ?? true)) {
          _model.paymentDetails = getJsonField(
            (_model.apiResCharge?.jsonBody ?? ''),
            r'''$''',
          );
          safeSetState(() {});
        }
      } else {
        return;
      }
    });

    WidgetsBinding.instance.addPostFrameCallback((_) => safeSetState(() {}));
  }

